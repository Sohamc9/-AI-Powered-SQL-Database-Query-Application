import { config } from '../config.js';
import { AiGeneratedSqlResponse } from './demoGenerator.js';

const SCHEMA_PROMPT = `
You are an expert SQL assistant for QueryPilot.
Database: SQLite.
Tables:
1. categories (id INTEGER PK, name TEXT, department TEXT, description TEXT)
2. customers (id INTEGER PK, name TEXT, email TEXT, country TEXT, customer_tier TEXT ['Standard', 'Premium', 'VIP', 'Enterprise'], signup_date TEXT, lifetime_spend REAL)
3. products (id INTEGER PK, name TEXT, category_id INTEGER, price REAL, stock_quantity INTEGER, rating REAL, is_active INTEGER, created_at TEXT)
4. orders (id INTEGER PK, customer_id INTEGER, order_date TEXT, status TEXT ['completed', 'shipped', 'processing', 'cancelled', 'refunded'], total_amount REAL, payment_method TEXT, shipping_city TEXT)
5. order_items (id INTEGER PK, order_id INTEGER, product_id INTEGER, quantity INTEGER, unit_price REAL, discount_percent REAL)
6. reviews (id INTEGER PK, product_id INTEGER, customer_id INTEGER, rating INTEGER [1-5], comment TEXT, review_date TEXT)

Guidelines:
- Return ONLY valid SQLite SQL and a concise explanation in JSON format.
- Output JSON structure:
{
  "sql": "SELECT ...;",
  "explanation": "Clear explanation of what the query accomplishes.",
  "tablesUsed": ["table1", "table2"]
}
`;

/**
 * Calls OpenAI API if configured
 */
export async function generateOpenAiSql(prompt: string): Promise<AiGeneratedSqlResponse> {
  if (!config.openaiApiKey) {
    throw new Error('OPENAI_API_KEY is not configured in server environment.');
  }

  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${config.openaiApiKey}`
    },
    body: JSON.stringify({
      model: config.openaiModel || 'gpt-4o-mini',
      messages: [
        { role: 'system', content: SCHEMA_PROMPT },
        { role: 'user', content: `Write a SQL query for: ${prompt}` }
      ],
      response_format: { type: 'json_object' },
      temperature: 0.1
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`OpenAI API error (${response.status}): ${errorText}`);
  }

  const data: any = await response.json();
  const content = data.choices?.[0]?.message?.content;
  const parsed = JSON.parse(content || '{}');

  return {
    sql: parsed.sql || 'SELECT * FROM customers LIMIT 10;',
    explanation: parsed.explanation || 'Query generated by OpenAI.',
    tablesUsed: parsed.tablesUsed || ['customers'],
    isDemoMode: false,
    provider: `OpenAI (${config.openaiModel})`
  };
}

/**
 * Calls Gemini API if configured
 */
export async function generateGeminiSql(prompt: string): Promise<AiGeneratedSqlResponse> {
  if (!config.geminiApiKey) {
    throw new Error('GEMINI_API_KEY is not configured in server environment.');
  }

  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${config.geminiApiKey}`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [
        {
          parts: [
            { text: `${SCHEMA_PROMPT}\nUser request: ${prompt}\nOutput valid JSON ONLY.` }
          ]
        }
      ],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.1
      }
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Gemini API error (${response.status}): ${errorText}`);
  }

  const data: any = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  const parsed = JSON.parse(text || '{}');

  return {
    sql: parsed.sql || 'SELECT * FROM customers LIMIT 10;',
    explanation: parsed.explanation || 'Query generated by Google Gemini.',
    tablesUsed: parsed.tablesUsed || ['customers'],
    isDemoMode: false,
    provider: 'Google Gemini (1.5-flash)'
  };
}
